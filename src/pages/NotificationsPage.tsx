import React, { useState, useEffect } from 'react';
import { useAuth } from '../context/AuthContext';
import {
  Bell,
  CheckCircle2,
  Trash2,
  Clock,
  ArrowDownLeft,
  ArrowUpRight,
  Shield,
  Zap,
} from 'lucide-react';
import {
  collection,
  query,
  where,
  orderBy,
  onSnapshot,
  doc,
  updateDoc,
  deleteDoc,
  writeBatch,
} from 'firebase/firestore';
import { db } from '../lib/firebase';
import { AppNotification } from '../types';

export const NotificationsPage: React.FC = () => {
  const { currentUser } = useAuth();
  const [notifications, setNotifications] = useState<AppNotification[]>([]);

  useEffect(() => {
    if (!currentUser) return;
    const q = query(
      collection(db, 'notifications'),
      where('uid', '==', currentUser.uid),
      orderBy('createdAt', 'desc')
    );
    const unsub = onSnapshot(
      q,
      (snap) => {
        const list: AppNotification[] = [];
        snap.forEach((d) => list.push({ ...d.data(), id: d.id } as AppNotification));
        setNotifications(list);
      },
      (error) => {
        console.warn('NotificationsPage listener notice:', error);
      }
    );
    return () => unsub();
  }, [currentUser]);

  const handleMarkAsRead = async (id: string) => {
    try {
      const ref = doc(db, 'notifications', id);
      await updateDoc(ref, { read: true });
    } catch (err) {
      console.error('Failed to mark read', err);
    }
  };

  const handleDelete = async (id: string) => {
    try {
      const ref = doc(db, 'notifications', id);
      await deleteDoc(ref);
    } catch (err) {
      console.error('Failed to delete notification', err);
    }
  };

  const handleMarkAllAsRead = async () => {
    try {
      const batch = writeBatch(db);
      notifications.filter((n) => !n.read).forEach((n) => {
        if (n.id) {
          batch.update(doc(db, 'notifications', n.id), { read: true });
        }
      });
      await batch.commit();
    } catch (err) {
      console.error('Failed to mark all read', err);
    }
  };

  return (
    <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-8 space-y-8">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <div className="flex items-center gap-2 text-xs font-bold text-emerald-400 uppercase tracking-wider mb-1">
            <Bell className="w-4 h-4" />
            <span>Event Dispatcher</span>
          </div>
          <h1 className="text-3xl font-extrabold text-white tracking-tight">Notifications</h1>
          <p className="text-sm text-slate-400 mt-1">
            Automated alerts generated by session completions, deposits, and ledger updates.
          </p>
        </div>

        {notifications.some((n) => !n.read) && (
          <button
            onClick={handleMarkAllAsRead}
            className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold rounded-xl border border-slate-700 transition-colors"
          >
            Mark All as Read
          </button>
        )}
      </div>

      {/* Notifications List */}
      <div className="space-y-3">
        {notifications.length === 0 ? (
          <div className="p-12 text-center rounded-2xl bg-slate-900 border border-slate-800 text-slate-500 text-xs">
            No notifications on record.
          </div>
        ) : (
          notifications.map((notif) => (
            <div
              key={notif.id || notif.notificationId}
              onClick={() => notif.id && !notif.read && handleMarkAsRead(notif.id)}
              className={`p-4 rounded-xl border transition-all flex items-start justify-between gap-4 cursor-pointer ${
                notif.read
                  ? 'bg-slate-950/60 border-slate-800/80 opacity-75'
                  : 'bg-slate-900 border-emerald-500/40 shadow-md'
              }`}
            >
              <div className="flex items-start gap-3">
                <div
                  className={`w-8 h-8 rounded-lg flex items-center justify-center shrink-0 mt-0.5 ${
                    notif.type.includes('SESSION')
                      ? 'bg-purple-500/10 text-purple-400'
                      : notif.type.includes('DEPOSIT')
                      ? 'bg-emerald-500/10 text-emerald-400'
                      : notif.type.includes('WITHDRAWAL')
                      ? 'bg-cyan-500/10 text-cyan-400'
                      : 'bg-slate-800 text-slate-300'
                  }`}
                >
                  <Zap className="w-4 h-4" />
                </div>

                <div>
                  <div className="flex items-center gap-2">
                    <h4 className="font-bold text-sm text-white">{notif.title}</h4>
                    {!notif.read && (
                      <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse" />
                    )}
                  </div>
                  <p className="text-xs text-slate-300 mt-1 leading-relaxed">{notif.message}</p>
                  <span className="text-[10px] text-slate-500 block mt-2">
                    {new Date(notif.createdAt).toLocaleString()}
                  </span>
                </div>
              </div>

              <button
                onClick={(e) => {
                  e.stopPropagation();
                  if (notif.id) handleDelete(notif.id);
                }}
                className="p-1.5 text-slate-500 hover:text-red-400 rounded-lg transition-colors"
                title="Delete notification"
              >
                <Trash2 className="w-4 h-4" />
              </button>
            </div>
          ))
        )}
      </div>
    </div>
  );
};
